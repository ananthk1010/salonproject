"""Evaluation runner for the golden set (docs/PHASE1_PLAN.md section 7).

Usage (from the repo root, with apps/api's venv active or on PYTHONPATH):
    python lab/jev_eval.py                  # replay mode, 1 run
    python lab/jev_eval.py --mode live       # calls the real gateway (needs JEV_API_KEY)
    python lab/jev_eval.py --runs 3          # repeat for the self-consistency / flip-rate check

Writes eval/results.json and eval/results.md. This is a starter
implementation against the 18-message starter golden set generated by
apps/api/scripts/generate_seed.py; docs/PHASE1_PLAN.md section 7 calls for
120 messages for the real Phase 1 evaluation (milestone M3).
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API_ROOT = ROOT / "apps" / "api"
sys.path.insert(0, str(API_ROOT))

from app.config import Settings  # noqa: E402
from app.jev.answers import ChoiceAnswer, ScoreAnswer  # noqa: E402
from app.jev.client import JevClient, JevUpstreamError  # noqa: E402
from app.jev.questions import FRUSTRATION_LEVELS, URGENCY_LEVELS  # noqa: E402
from app.jev.replay import ReplayStore  # noqa: E402
from app.jev.state_builder import build_state  # noqa: E402
from app.policy.route import route  # noqa: E402
from app.rules.hours import is_open  # noqa: E402

GOLDEN_PATH = ROOT / "eval" / "golden.jsonl"
FIXTURES_DIR = ROOT / "eval" / "fixtures"
RESULTS_JSON = ROOT / "eval" / "results.json"
RESULTS_MD = ROOT / "eval" / "results.md"

BRANCHES = {b["id"]: b for b in json.loads((API_ROOT / "data" / "seed" / "branches.json").read_text())}
CUSTOMERS = {c["id"]: c for c in json.loads((API_ROOT / "data" / "seed" / "customers.json").read_text())}


def load_golden() -> list[dict]:
    lines = GOLDEN_PATH.read_text(encoding="utf-8").strip().splitlines()
    return [json.loads(l) for l in lines]


def run_once(mode: str) -> list[dict]:
    """Returns one row per golden-set message: predicted answers + usage + latency."""
    settings = Settings(jev_mode=mode)
    replay_store = ReplayStore(FIXTURES_DIR)
    jev_client = JevClient(settings) if mode == "live" else None

    rows = []
    for item in load_golden():
        branch = BRANCHES[item["branchId"]]
        customer = CUSTOMERS.get(item["customerId"])
        state = build_state(
            customer=customer, tier="unknown-in-eval", recent_visits=[],
            interaction_text=item["text"], interaction_channel=item["channel"], branch=branch,
        )
        if mode == "live":
            try:
                answers = jev_client.evaluate(state)
            except JevUpstreamError as exc:
                print(f"  [warn] live call failed for {item['id']}: {exc}; falling back to replay")
                answers = replay_store.get(item["id"])
        else:
            answers = replay_store.get(item["id"])

        received_at = datetime.fromisoformat(item["receivedAt"])
        intent = answers.intent_choice() or "other"
        decision = route(intent, branch, received_at)
        hours_ok = is_open(branch, received_at)
        expected_confirmed = item["label"]["intent"] == "book_appointment" and hours_ok
        expected_action = (
            "confirmed" if expected_confirmed
            else "rejected_outside_hours" if item["label"]["intent"] == "book_appointment"
            else "recorded"
        )

        rows.append({
            "id": item["id"],
            "label": item["label"],
            "answers": {k: v.model_dump() for k, v in answers.answers.items()},
            "action": decision.action,
            "expected_action": expected_action,
            "policy_correct": decision.action == expected_action,
            "latency_ms": answers.latency_ms,
            "input_tokens": answers.usage.input_tokens,
            "mode": answers.mode,
        })
    if jev_client:
        jev_client.close()
    return rows


def _predicted_choice(row: dict, question: str) -> str | None:
    a = row["answers"].get(question)
    return a["choice"] if a and a["type"] == "choice" else None


def _predicted_score_index(row: dict, question: str) -> int | None:
    a = row["answers"].get(question)
    return round(a["score"]) if a and a["type"] == "score" else None


def score_accuracy(rows: list[dict]) -> dict:
    out = {}
    for q in ("intent", "service_category"):
        correct = sum(1 for r in rows if _predicted_choice(r, q) == r["label"][q])
        out[q] = {"accuracy": correct / len(rows), "n": len(rows)}
    for q in ("urgency", "frustration"):
        correct = sum(1 for r in rows if _predicted_score_index(r, q) == r["label"][q])
        out[q] = {"accuracy": correct / len(rows), "n": len(rows)}
    for q in ("wants_specific_stylist", "wants_callback"):
        correct = 0
        for r in rows:
            a = r["answers"].get(q)
            predicted = bool(a and a["type"] == "noul" and a["noul"] >= 0.5)
            correct += int(predicted == bool(r["label"][q]))
        out[q] = {"accuracy": correct / len(rows), "n": len(rows)}
    return out


def reliability_buckets(rows: list[dict]) -> dict:
    """Confidence bucket -> observed accuracy, for intent only (an
    observational calibration study; Phase 1's policy does not act on
    confidence at all -- see architecture doc section 13)."""
    buckets: dict[str, list[bool]] = {"low (<0.5)": [], "medium (0.5-0.9)": [], "high (>=0.9)": []}
    for r in rows:
        a = r["answers"].get("intent")
        if not a:
            continue
        conf = a["confidence"]
        correct = a["choice"] == r["label"]["intent"]
        if conf < 0.5:
            buckets["low (<0.5)"].append(correct)
        elif conf < 0.9:
            buckets["medium (0.5-0.9)"].append(correct)
        else:
            buckets["high (>=0.9)"].append(correct)
    return {
        k: {"n": len(v), "accuracy": (sum(v) / len(v) if v else None)}
        for k, v in buckets.items()
    }


def policy_regression(rows: list[dict]) -> dict:
    wrong = [r["id"] for r in rows if not r["policy_correct"]]
    return {"total": len(rows), "correct": len(rows) - len(wrong), "mismatches": wrong}


def flip_rate(all_runs: list[list[dict]]) -> float | None:
    if len(all_runs) < 2:
        return None
    by_id: dict[str, list[dict]] = {}
    for run in all_runs:
        for r in run:
            by_id.setdefault(r["id"], []).append(r)
    flips = 0
    total = 0
    for _id, variants in by_id.items():
        first = variants[0]["answers"].get("intent", {}).get("choice")
        for v in variants[1:]:
            total += 1
            if v["answers"].get("intent", {}).get("choice") != first:
                flips += 1
    return flips / total if total else None


def cost_and_latency(rows: list[dict]) -> dict:
    tokens = [r["input_tokens"] for r in rows]
    latencies = [r["latency_ms"] for r in rows if r["mode"] == "live"]
    out = {
        "mean_input_tokens": statistics.mean(tokens) if tokens else 0,
        "estimated_cost_usd_per_call": (statistics.mean(tokens) if tokens else 0) * 0.042 / 1_000_000,
    }
    if latencies:
        out["p50_latency_ms"] = statistics.median(latencies)
        out["p95_latency_ms"] = sorted(latencies)[max(0, int(len(latencies) * 0.95) - 1)]
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["live", "replay"], default="replay")
    parser.add_argument("--runs", type=int, default=1)
    args = parser.parse_args()

    print(f"Running eval in {args.mode} mode, {args.runs} run(s), "
          f"{len(load_golden())} golden-set messages...")

    all_runs = []
    for i in range(args.runs):
        t0 = time.time()
        rows = run_once(args.mode)
        all_runs.append(rows)
        print(f"  run {i + 1}/{args.runs} done in {time.time() - t0:.1f}s")

    last = all_runs[-1]
    results = {
        "mode": args.mode,
        "runs": args.runs,
        "n_messages": len(last),
        "accuracy": score_accuracy(last),
        "reliability": reliability_buckets(last),
        "policy_regression": policy_regression(last),
        "cost_and_latency": cost_and_latency(last),
        "flip_rate": flip_rate(all_runs),
    }
    RESULTS_JSON.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_JSON.write_text(json.dumps(results, indent=2), encoding="utf-8")

    md = [f"# Jev evaluation results ({args.mode} mode, {args.runs} run(s), {len(last)} messages)\n"]
    if args.mode == "replay":
        md.append(
            "> **Replay mode caveat.** These fixtures were generated directly from the\n"
            "> golden-set labels (see `apps/api/scripts/generate_seed.py`), so 100% accuracy\n"
            "> here is circular, not a real result. It confirms the harness and the policy\n"
            "> logic are wired correctly. Run `--mode live` against the real gateway for a\n"
            "> meaningful number, and see docs/PHASE1_PLAN.md section 7 for the plan to grow\n"
            "> the golden set to 120 messages (milestone M3).\n"
        )
    md.append("## Accuracy per question\n")
    md.append("| Question | Accuracy | n |\n|---|---|---|")
    for q, v in results["accuracy"].items():
        md.append(f"| {q} | {v['accuracy']:.0%} | {v['n']} |")
    md.append("\n## Confidence calibration (intent, observational -- not used for routing)\n")
    md.append("| Bucket | n | Accuracy |\n|---|---|---|")
    for b, v in results["reliability"].items():
        acc = f"{v['accuracy']:.0%}" if v["accuracy"] is not None else "n/a"
        md.append(f"| {b} | {v['n']} | {acc} |")
    md.append("\n## Policy regression (deterministic, not a model score)\n")
    pr = results["policy_regression"]
    md.append(f"{pr['correct']}/{pr['total']} correct. Mismatches: {pr['mismatches'] or 'none'}\n")
    md.append("## Cost and latency\n")
    cl = results["cost_and_latency"]
    md.append(f"- Mean input tokens per call: {cl['mean_input_tokens']:.0f}")
    md.append(f"- Estimated cost per call: ${cl['estimated_cost_usd_per_call']:.6f}")
    if "p50_latency_ms" in cl:
        md.append(f"- Latency p50/p95: {cl['p50_latency_ms']:.0f} ms / {cl['p95_latency_ms']:.0f} ms")
    if results["flip_rate"] is not None:
        md.append(f"\n## Self-consistency\nFlip rate across {args.runs} runs: {results['flip_rate']:.1%}")
    RESULTS_MD.write_text("\n".join(md) + "\n", encoding="utf-8")

    print(f"\nwrote {RESULTS_JSON}")
    print(f"wrote {RESULTS_MD}")


if __name__ == "__main__":
    main()
